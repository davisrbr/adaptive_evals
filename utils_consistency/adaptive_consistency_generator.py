from typing import List, Optional, Dict, Tuple
from datetime import datetime
from openai import OpenAI
import pandas as pd
import logging 
from dataclasses import dataclass
import os
import json

@dataclass
class GenerationConfig:
    n_questions: int
    samples_per_bucket: Dict[str, int]
    samples_per_consistency: Dict[str, int]
    model: str = "gpt-4o"
    temperature: float = 0.7
    checkpoint_dir: str = "adaptive_consistency_checkpoints"

class AdversarialQuestionGenerator:
    def __init__(self, config: GenerationConfig):
        self.config = config
        self.client = OpenAI()
        os.makedirs(config.checkpoint_dir, exist_ok=True)
    
    def save_to_csv(self, questions: List[Dict], timestamp: str) -> pd.DataFrame:
        """Convert generated questions to DataFrame and save to CSV."""
        rows = []
        for q in questions:
            row = {
                'question_P_title': q['original']['title'],
                'question_P_body': q['original']['body'],
                'question_Q_title': q['second']['title'],
                'question_Q_body': q['second']['body'],
                'consistency_type': q['consistency']['type'],
                'challenge_factors': ', '.join(q['original']['challenge_factors']),
                'challenge_rationale': q['consistency']['challenge_rationale']
            }
            
            # Add R questions for AND/OR types
            if q['consistency']['type'].lower() in ['and', 'or']:
                row.update({
                    'question_R_title': q['combined']['title'],
                    'question_R_body': q['combined']['body']
                })
                
            rows.append(row)
        
        df = pd.DataFrame(rows)
        output_path = f'{self.config.checkpoint_dir}/generated_questions_{timestamp}.csv'
        df.to_csv(output_path, index=False)
        return df

    def bucket_questions(self, df: pd.DataFrame) -> Dict[str, Dict[str, pd.DataFrame]]:
        """Create performance buckets for each consistency type."""
        consistency_buckets = {}
        
        for consistency_type in df['consistency_type'].unique():
            type_df = df[df['consistency_type'] == consistency_type].copy()
            if len(type_df) == 0:
                continue
                
            scores = type_df['consistency_score']
            buckets = {
                'worst': type_df[scores >= scores.quantile(0.75)],
                'poor': type_df[(scores >= scores.quantile(0.5)) & (scores < scores.quantile(0.75))],
                'medium': type_df[(scores >= scores.quantile(0.25)) & (scores < scores.quantile(0.5))],
                'best': type_df[scores < scores.quantile(0.25)]
            }
            
            # Sample from each bucket according to config
            sampled_buckets = {}
            for bucket_name, bucket_df in buckets.items():
                if bucket_name in self.config.samples_per_bucket:
                    n_samples = min(self.config.samples_per_bucket[bucket_name], len(bucket_df))
                    sampled_buckets[bucket_name] = bucket_df.sample(n=n_samples)
            
            consistency_buckets[consistency_type] = sampled_buckets
            
        return consistency_buckets

    def _create_prompt_header(self) -> str:
        return """You are an expert in analyzing forecasting models and generating challenging questions. You'll analyze question pairs, along with forecasts generated by an LLM forecaster along with their consistency scores and then generate new challenging questions.

        DEFINITIONS OF CONSISTENCY TYPES:
        1. Logical Negation (NOT): 
        - Requires questions P and Q only
        - Q must be the exact logical negation of P
        - Example:
            P: "Will SpaceX launch Starship in 2024?"
            Q: "Will SpaceX NOT launch Starship in 2024?"
            (Q is the exact logical negation of P, P(Q) = 1 - P(P))

        2. Consequence: 
        - Requires questions P and Q only
        - Q must be a logical prerequisite for P
        - P(Q) should be greater than P(P)
        - Example:
            P: "Will computers in Italy send emails in 2050?"
            Q: "Will computers in Italy have internet?"
            (Q is necessary for P, as you can't send emails without internet)

        3. Paraphrase: 
        - Requires questions P and Q only
        - Q must be a restatement of P with exactly the same meaning
        - P(Q) should equal P(P)
        - Example:
            P: "Will global temperatures rise by 2°C by 2030?"
            Q: "Will Earth's average temperature increase by 2 degrees Celsius before 2031?"
            (Same meaning, different wording)

        4. AND: 
        - Requires questions P, Q, and R
        - R must be the logical conjunction of P and Q
        - R should be true if and only if both P and Q are true
        - Example:
            P: "Will SpaceX launch Starship in 2024?"
            Q: "Will Blue Origin launch New Glenn in 2024?"
            R: "Will both SpaceX's Starship and Blue Origin's New Glenn launch in 2024?"
            (R is true only if both P AND Q are true)

        5. OR: 
        - Requires questions P, Q, and R
        - R must be the logical disjunction of P and Q
        - R should be true if either P or Q (or both) are true
        - Example:
            P: "Will the US win Olympic gold in basketball?"
            Q: "Will the US win Olympic gold in swimming?"
            R: "Will the US win Olympic gold in either basketball or swimming?"
            (R is true if either P OR Q is true)

        PART 1: EXAMPLE QUESTIONS BY CONSISTENCY TYPE AND PERFORMANCE
        """

    def _format_example(self, row: pd.Series, consistency_type: str) -> str:
        example = f"""
Original Question (P): {row['question_P_title']}
Original Body: {row['question_P_body']}
"""
        
        if consistency_type in ['and', 'or']:
            example += f"""
Second Question (Q): {row['question_Q_title']}
Q Body: {row['question_Q_body']}
Combined Question (R): {row['question_R_title']}
R Body: {row['question_R_body']}
Consistency Score: {row['consistency_score']:.4f}
P Probability: {row['question_P_forecast_probability']:.4f}
Q Probability: {row['question_Q_forecast_probability']:.4f}
R Probability: {row['question_R_forecast_probability']:.4f}
"""
        else:
            example += f"""
Consistency Question (Q): {row['question_Q_title']}
Q Body: {row['question_Q_body']}
Consistency Score: {row['consistency_score']:.4f}
P Probability: {row['question_P_forecast_probability']:.4f}
Q Probability: {row['question_Q_forecast_probability']:.4f}
"""
        return example + "---\n"
    
    def _add_examples(self, consistency_buckets: Dict[str, Dict[str, pd.DataFrame]]) -> str:
        """Add example questions with their performance metrics."""
        examples = ""
        
        for consistency_type, buckets in consistency_buckets.items():
            examples += f"\n\n=== {consistency_type.upper()} Examples ===\n"
            
            for bucket_name, bucket_df in buckets.items():
                examples += f"\n{bucket_name.upper()} Performance Examples:\n"
                
                for _, row in bucket_df.iterrows():
                    examples += self._format_example(row, consistency_type)
        
        return examples

    def _create_prompt_instructions(self) -> str:
        json_format = """{
    "question_pairs": [
        {
            "original": {
                "title": "Question P title",
                "body": "Full question P body with resolution criteria",
                "challenge_factors": ["List specific factors that make this pair/triplet challenging"]
            },
            "second": {
                "title": "Question Q title",
                "body": "Full question Q body with resolution criteria"
            },
            "combined": {
                "title": "Question R title (only for AND/OR)",
                "body": "Full question R body (only for AND/OR)"
            },
            "consistency": {
                "type": "not|consequence|paraphrase|and|or",
                "challenge_rationale": "Explain why this consistency type was chosen and why it's challenging"
            }
        }
    ]
}"""

        return f"""
PART 2: GENERATE NEW CHALLENGING QUESTIONS
1. First, analyze the patterns in these questions and cite examples while reasoning about the below questions, focusing on:
- Which consistency type tends to be most challenging and why? 
- What types of questions are most challenging for each consistency type and why, cite the examples above.
- What patterns and factors distinguish good vs poor performance? 
- Based on the forecasting results provided, identify at least three specific logical complexities or challenging aspects that make forecasting and logical consistencies difficult for an LLM.


2. Then, generate {self.config.n_questions} challenging question pairs/triplets:

For each question you generate, you must:
1. Specify the consistency type (NOT, Consequence, Paraphrase, AND, or OR)
2. Provide the required questions based on the type:
- For NOT, Consequence, Paraphrase: Provide P and Q
- For AND, OR: Provide P, Q, and R
3. Ensure the logical relationship matches the consistency type
4. Include challenge factors and rationale for why the question pair/triplet is challenging

You can either:
1. Generate completely new question pairs/triplets
2. Combine existing questions in meaningful ways
3. Create variations of existing questions

Most importantly, make sure the questions are challening and diverse (in both topic and consistency type).

Format your response exactly as follows:

<Begin Analysis>
[Your analysis of patterns across consistency types and performance levels, listing at least three specific challenging aspects to incorporate and tying them back to the forecasting results above]
<End Analysis>

<Begin Questions>
[Generate {self.config.n_questions} question pairs/triplets in this exact JSON format]
{json_format}
<End Questions>

Generate at least {self.config.n_questions} challenging question pairs/triplets. Most importantly, provide them exactly in the format specified above.
"""

    def create_prompt(self, consistency_buckets: Dict[str, Dict[str, pd.DataFrame]]) -> str:
        prompt = self._create_prompt_header()
        prompt += self._add_examples(consistency_buckets)
        prompt += self._create_prompt_instructions()
        return prompt

    def generate(self, prompt: str) -> str:
        """Generate questions using the OpenAI API."""
        try:
            response = self.client.chat.completions.create(
                model=self.config.model,
                messages=[{"role": "user", "content": prompt}],
                temperature=self.config.temperature
            )
            return response.choices[0].message.content
        except Exception as e:
            logging.error(f"Error in API call: {str(e)}")
            raise

    def parse_generation_response(self, response: str, timestamp: str) -> Tuple[str, List[Dict]]:
        """Parse the generated response into analysis and questions."""
        try:
            # Extract analysis
            analysis_start = response.find("<Begin Analysis>") + len("<Begin Analysis>")
            analysis_end = response.find("<End Analysis>")
            analysis = response[analysis_start:analysis_end].strip()
            
            # Extract questions JSON
            questions_start = response.find("<Begin Questions>") + len("<Begin Questions>")
            questions_end = response.find("<End Questions>")
            questions_json = response[questions_start:questions_end].strip()
            
            # Remove markdown code block markers and any extra whitespace
            if "```json" in questions_json:
                # If the response includes markdown formatting
                json_start = questions_json.find("{")
                json_end = questions_json.rfind("}") + 1
                if json_start != -1 and json_end != -1:
                    questions_json = questions_json[json_start:json_end]
            
            # Parse JSON
            try:
                questions_data = json.loads(questions_json)
                logging.info(f"Successfully parsed {len(questions_data['question_pairs'])} questions")
                return analysis, questions_data['question_pairs']
            except json.JSONDecodeError as je:
                logging.error(f"JSON parsing error: {str(je)}")
                logging.error(f"Attempted to parse: {questions_json}")
                raise
                
        except Exception as e:
            logging.error(f"Error in parse_generation_response: {str(e)}")
            logging.error(f"Raw response: {response}")
            raise

    def save_generation(self, prompt: str, response: str, timestamp: str) -> None:
        """Save the raw generation outputs."""
        # Save prompt
        prompt_path = f'{self.config.checkpoint_dir}/prompt_{timestamp}.txt'
        with open(prompt_path, 'w') as f:
            f.write(prompt)
        
        # Save raw response
        response_path = f'{self.config.checkpoint_dir}/raw_response_{timestamp}.txt'
        with open(response_path, 'w') as f:
            f.write(response)
            
        logging.info(f"Saved generation artifacts to {self.config.checkpoint_dir}")

    def save_to_csv(self, questions: List[Dict], timestamp: str) -> pd.DataFrame:
        """Save generated questions to CSV."""
        rows = []
        for q in questions:
            row = {
                'question_P_title': q['original']['title'],
                'question_P_body': q['original']['body'],
                'question_P_challenge_factors': ','.join(q['original']['challenge_factors']),
                'question_Q_title': q['second']['title'],
                'question_Q_body': q['second']['body'],
                'consistency_type': q['consistency']['type'],
                'consistency_challenge_rationale': q['consistency']['challenge_rationale']
            }
            
            # Add R questions for AND/OR types
            if q['consistency']['type'] in ['and', 'or']:
                row.update({
                    'question_R_title': q['combined']['title'],
                    'question_R_body': q['combined']['body']
                })
            
            rows.append(row)
        
        df = pd.DataFrame(rows)
        csv_path = f'{self.config.checkpoint_dir}/generated_questions_{timestamp}.csv'
        df.to_csv(csv_path, index=False)
        logging.info(f"Saved generated questions to {csv_path}")
        return df

def main_adversarial_generation(
    input_csv: str,
    config: GenerationConfig
) -> Tuple[str, pd.DataFrame]:
    """Main function to generate adversarial questions."""
    try:
        # Load data
        df = pd.read_csv(input_csv)
        logging.info(f"Loaded {len(df)} rows from {input_csv}")
        
        # Initialize generator
        generator = AdversarialQuestionGenerator(config)
        
        # Create buckets
        consistency_buckets = generator.bucket_questions(df)
        
        # Create prompt
        prompt = generator.create_prompt(consistency_buckets)
        
        # Generate questions
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        response = generator.generate(prompt)
        
        # Save all outputs
        generator.save_generation(prompt, response, timestamp)
        
        # Parse response
        analysis, questions = generator.parse_generation_response(response, timestamp)
        
        # Save results to CSV
        generated_df = generator.save_to_csv(questions, timestamp)
        
        print("Generation complete! Check the outputs in:", config.checkpoint_dir)
        print(f"Raw response saved to: {config.checkpoint_dir}/raw_response_{timestamp}.txt")
        print(f"Generation log saved to: {config.checkpoint_dir}/generation_{timestamp}.log")
        print(f"Generated questions saved to: {config.checkpoint_dir}/generated_questions_{timestamp}.csv")
        
        return analysis, generated_df
        
    except Exception as e:
        logging.error(f"Error in adversarial generation: {str(e)}")
        raise

