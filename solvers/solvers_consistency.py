        if not sample.metadata.get('consistency_checks'):
            return None, None, -1
            
        worst_score = -1
        worst_type = None
        worst_check = None
        
        for ct, checks in sample.metadata['consistency_checks'].items():
            # Get specific score for this consistency check if available
            # Otherwise use overall score
            score = checks.get('score', sample.scores['consistency_scorer'].value['overall_score'])
            if score > worst_score:
                worst_score = score
                worst_type = ct
                worst_check = checks
                
        return worst_type, worst_check, worst_score

    
