#Checking Novelty of adaptive generatied question by comparing cosine sim with initial dataset
class NoveltyChecker:
    def __init__(self, 
                 model_name: str = 'sentence-transformers/all-mpnet-base-v2', 
                 similarity_threshold: float = 0.8):
        """Initialize NoveltyChecker with specified model and threshold."""
        self.model = SentenceTransformer(model_name)
        self.threshold = similarity_threshold
        self.existing_titles: List[str] = []  # Store all question titles
        self.title_embeddings = None  # Will store tensor of embeddings
        self.repeated_questions: Set[str] = set()
        
    def initialize_with_dataset(self, dataset_questions: List[str]):
        """Initialize with existing dataset questions."""
        if not dataset_questions:
            return
        
        self.existing_titles = dataset_questions
        self.title_embeddings = self.model.encode(dataset_questions, convert_to_tensor=True)
        
    def _get_all_titles_from_question(self, question: Dict) -> List[str]:
        """Extract all titles from a question pair/triplet."""
        titles = [question['original']['title'], question['second']['title']]
        if 'combined' in question and question['combined']['title']:
            titles.append(question['combined']['title'])
        return titles
    
    def _compute_max_similarity(self, titles: List[str]) -> tuple[float, str, str]:
        """
        Compute maximum similarity between given titles and existing titles.
        Returns (max_similarity, new_title, existing_title) that gave max similarity.
        """
        if not self.existing_titles:
            return 0.0, "", ""
            
        # Get embeddings for new titles
        new_embeddings = self.model.encode(titles, convert_to_tensor=True)
        
        # Compute similarities between all new titles and all existing titles
        similarities = torch.nn.functional.cosine_similarity(
            new_embeddings.unsqueeze(1),  # [new_titles, 1, embedding_dim]
            self.title_embeddings.unsqueeze(0),  # [1, existing_titles, embedding_dim]
            dim=2
        )
        
        # Get maximum similarity and indices
        max_sim_flat_idx = torch.argmax(similarities.flatten())
        max_sim = similarities.flatten()[max_sim_flat_idx].item()
        
        # Convert flat index to 2D indices
        new_idx = max_sim_flat_idx // similarities.shape[1]
        existing_idx = max_sim_flat_idx % similarities.shape[1]
        
        return max_sim, titles[new_idx], self.existing_titles[existing_idx]
    
    def is_novel(self, question: Dict) -> bool:
        """
        Check if a question is novel by comparing all its titles against existing titles.
        """
        # Get all titles from the question
        new_titles = self._get_all_titles_from_question(question)
        
        # Compute maximum similarity
        max_sim, most_similar_new, most_similar_existing = self._compute_max_similarity(new_titles)

         # Log similarity details for each question
        logging.info(f"\n=== Novelty Check ===")
        logging.info(f"Max cosine similarity: {max_sim:.3f}")
        logging.info(f"New question: {most_similar_new}")
        logging.info(f"Most similar existing: {most_similar_existing}")
        logging.info(f"Threshold: {self.threshold}")
        logging.info(f"Novel? {max_sim <= self.threshold}")
        
        if max_sim > self.threshold:
            logging.warning(f"Question not novel. Max similarity: {max_sim:.3f}")
            logging.warning(f"Similar titles:\nNew: {most_similar_new}\nExisting: {most_similar_existing}")
            self.repeated_questions.add(most_similar_new)
            return False
            
        return True
    
    def add_generated_question(self, question: Dict):
        """Add a newly generated question to the pool of existing questions."""
        new_titles = self._get_all_titles_from_question(question)
        
        # Add new titles to existing titles list
        self.existing_titles.extend(new_titles)
        
        # Update embeddings
        new_embeddings = self.model.encode(new_titles, convert_to_tensor=True)
        if self.title_embeddings is None:
            self.title_embeddings = new_embeddings
        else:
            self.title_embeddings = torch.cat([self.title_embeddings, new_embeddings])


